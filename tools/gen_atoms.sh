#!/bin/sh
# Regenerate src/qjs_builtin_atoms.h from a real QuickJS quickjs-atom.h.
#
# Usage:
#   tools/gen_atoms.sh /path/to/quickjs-atom.h > src/qjs_builtin_atoms.h
#
# The generated header contains TWO built-in atom tables:
#
#   * vanilla  - the stock QuickJS table.  JS_ATOM_END == 227 for the
#                2024-01-13 release (226 DEF() entries + JS_ATOM_NULL).
#   * frida    - Frida's QuickJS fork inserts one extra built-in atom,
#                "prepareStackTrace", between "stack" (idx 54) and "name"
#                (idx 55).  Every later built-in atom shifts up by one and
#                JS_ATOM_END becomes 228.
#
# The decompiler auto-detects which table a bytecode file uses, but the
# tables must exist for that detection to work.
set -e

ATOM_H="$1"
[ -f "$ATOM_H" ] || { echo "error: $ATOM_H not found" >&2; exit 1; }

# The Frida fork inserts its extra atom right after the vanilla entry
# "stack" (index 54, 0-based counting JS_ATOM_NULL as 0).
FRIDA_EXTRA_INDEX=55
FRIDA_EXTRA_NAME="prepareStackTrace"

extract_atoms() {
    awk '
    /^DEF\(/ {
        s = $0
        sub(/^DEF\([^,]*,[ \t]*"/, "", s)
        sub(/".*$/, "", s)
        gsub(/\\/, "\\\\", s)
        gsub(/"/, "\\\"", s)
        print s
    }
    ' "$ATOM_H"
}

N=$(extract_atoms | wc -l)
# vanilla table: JS_ATOM_NULL (index 0) + N entries -> JS_ATOM_END == N + 1
VANILLA_END=$((N + 1))
FRIDA_END=$((VANILLA_END + 1))

emit_table() {
    # $1 = extra atom name ("" for none), $2 = insertion index (0 = none)
    extra_name="$1"
    extra_idx="$2"
    # JS_ATOM_NULL occupies index 0, so the DEF() entries start at index 1.
    i=1
    extract_atoms | while IFS= read -r a; do
        if [ -n "$extra_name" ] && [ "$i" -eq "$extra_idx" ]; then
            printf '    "%s", /* index %d */\n' "$extra_name" "$i"
            i=$((i + 1))
        fi
        printf '    "%s", /* index %d */\n' "$a" "$i"
        i=$((i + 1))
    done
}

cat <<HEADER
/*
 * qjs_builtin_atoms.h - Built-in QuickJS atoms
 *
 * Auto-generated by tools/gen_atoms.sh from quickjs-atom.h.
 * Do not edit by hand - regenerate with:
 *
 *     tools/gen_atoms.sh /path/to/quickjs-atom.h > src/qjs_builtin_atoms.h
 *
 * Two tables are provided:
 *
 *   qjs_atoms_vanilla[]  stock QuickJS.  JS_ATOM_END = $VANILLA_END.
 *   qjs_atoms_frida[]    Frida's QuickJS fork, which adds the extra
 *                         built-in atom "$FRIDA_EXTRA_NAME" at index
 *                         $FRIDA_EXTRA_INDEX.  JS_ATOM_END = $FRIDA_END.
 *
 * Both tables include the JS_ATOM_NULL placeholder at index 0.
 */
#ifndef QJS_BUILTIN_ATOMS_H
#define QJS_BUILTIN_ATOMS_H

#include <stddef.h>   /* NULL */

#define QJS_VANILLA_ATOM_END $VANILLA_END
#define QJS_FRIDA_ATOM_END   $FRIDA_END

#define QJS_FRIDA_EXTRA_ATOM_INDEX $FRIDA_EXTRA_INDEX
#define QJS_FRIDA_EXTRA_ATOM_NAME "$FRIDA_EXTRA_NAME"

/* Atom flavour used when resolving a built-in atom index. */
typedef enum {
    QJS_ATOM_FLAVOR_VANILLA = 0,
    QJS_ATOM_FLAVOR_FRIDA   = 1
} qjs_atom_flavor_t;

#ifdef JARONA_DEFINE_ATOM_TABLE

const char *qjs_atoms_vanilla[QJS_VANILLA_ATOM_END] = {
    NULL, /* index 0 = JS_ATOM_NULL */
HEADER

emit_table "" 0

cat <<MIDDLE
};

const char *qjs_atoms_frida[QJS_FRIDA_ATOM_END] = {
    NULL, /* index 0 = JS_ATOM_NULL */
MIDDLE

emit_table "$FRIDA_EXTRA_NAME" "$FRIDA_EXTRA_INDEX"

cat <<FOOTER
};

#endif /* JARONA_DEFINE_ATOM_TABLE */

#endif /* QJS_BUILTIN_ATOMS_H */
FOOTER
